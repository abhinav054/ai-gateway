@dataclass
class SQLiteKeyStore:
    def list_keys(self, gateway_id: str) -> list[dict]:
        with self.connect() as conn:
            rows = conn.execute(
                "SELECT key_hash, name, created_at FROM gateway_keys WHERE gateway_id = ? ORDER BY created_at DESC, id DESC",
                (gateway_id,),
            ).fetchall()
        return [{"id": row[0], "name": row[1], "createdAt": str(row[2])} for row in rows]

    path: Path = DEFAULT_SQLITE_PATH

    def initialize(self) -> None:
        with self.connect() as conn:
            conn.execute("CREATE TABLE IF NOT EXISTS gateway_objects (id TEXT PRIMARY KEY, definition TEXT NOT NULL)")
            conn.execute(SQLITE_CREATE_KEYS_TABLE_SQL)
            conn.execute(SQLITE_CREATE_ROUTES_TABLE_SQL)
            ensure_sqlite_columns(
                conn,
                "gateway_keys",
                {
                    "provider": "TEXT",
                    "api_key": "TEXT",
                    "base_url": "TEXT",
                    "gateway_id": "TEXT REFERENCES gateway_objects(id)",
                },
            )

    def add_key_hash(
        self,
        key_hash: str,
        name: str | None = None,
        provider: str | None = None,
        api_key: str | None = None,
        base_url: str | None = None,
        gateway_id: str | None = None,
    ) -> None:
        with self.connect() as conn:
            conn.execute(
                """
                INSERT INTO gateway_keys (key_hash, name, provider, api_key, base_url, gateway_id)
                VALUES (?, ?, ?, ?, ?, ?)
                ON CONFLICT(key_hash) DO UPDATE SET
                    name = excluded.name,
                    provider = excluded.provider,
                    api_key = excluded.api_key,
                    base_url = excluded.base_url,
                    gateway_id = excluded.gateway_id
                """,
                (key_hash, name, provider, api_key, base_url, gateway_id),
            )

    def has_key_hash(self, key_hash: str) -> bool:
        with self.connect() as conn:
            row = conn.execute(
                "SELECT 1 FROM gateway_keys WHERE key_hash = ? LIMIT 1",
                (key_hash,),
            ).fetchone()
        return row is not None

    def get_key(self, key_hash: str) -> GatewayKey | None:
        with self.connect() as conn:
            row = conn.execute(
                """
                SELECT key_hash, name, provider, api_key, base_url, gateway_id
                FROM gateway_keys
                WHERE key_hash = ?
                LIMIT 1
                """,
                (key_hash,),
            ).fetchone()
        return gateway_key_from_row(row)

    def upsert_route(self, name: str, provider: str | None, api_key: str, base_url: str) -> None:
        with self.connect() as conn:
            conn.execute(
                """
                INSERT INTO gateway_routes (name, provider, api_key, base_url, updated_at)
                VALUES (?, ?, ?, ?, CURRENT_TIMESTAMP)
                ON CONFLICT(name) DO UPDATE SET
                    provider = excluded.provider,
                    api_key = excluded.api_key,
                    base_url = excluded.base_url,
                    updated_at = CURRENT_TIMESTAMP
                """,
                (name, provider, api_key, base_url),
            )

    def get_route(self, name: str) -> RoutingConfig | None:
        with self.connect() as conn:
            row = conn.execute(
                """
                SELECT name, provider, api_key, base_url
                FROM gateway_routes
                WHERE name = ?
                LIMIT 1
                """,
                (name,),
            ).fetchone()
        return routing_config_from_row(row)

    def list_routes(self) -> list[RoutingConfig]:
        with self.connect() as conn:
            rows = conn.execute(
                "SELECT name, provider, api_key, base_url FROM gateway_routes ORDER BY name"
            ).fetchall()
        return [RoutingConfig(*row) for row in rows]

    def upsert_gateway(self, gateway: Gateway) -> None:
        with self.connect() as conn:
            conn.execute(
                "INSERT INTO gateway_objects (id, definition) VALUES (?, ?) "
                "ON CONFLICT(id) DO UPDATE SET definition = excluded.definition",
                (gateway.id, gateway.model_dump_json()),
            )

    def get_gateway(self, gateway_id: str) -> Gateway | None:
        with self.connect() as conn:
            row = conn.execute("SELECT definition FROM gateway_objects WHERE id = ?", (gateway_id,)).fetchone()
        return Gateway.model_validate_json(row[0]) if row else None

    def connect(self) -> sqlite3.Connection:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        conn = sqlite3.connect(self.path)
        conn.execute("PRAGMA foreign_keys = ON")
        return conn


