def build_key_store() -> KeyStore:
    backend = os.getenv("GATEWAY_KEY_STORE", "sqlite").lower()

    if backend == "sqlite":
        return SQLiteKeyStore(Path(os.getenv("GATEWAY_SQLITE_PATH", str(DEFAULT_SQLITE_PATH))))

    if backend in {"postgres", "postgresql"}:
        dsn = os.getenv("GATEWAY_POSTGRES_DSN")
        if not dsn:
            raise RuntimeError("GATEWAY_POSTGRES_DSN is required when GATEWAY_KEY_STORE=postgres")

        redis_url = os.getenv("GATEWAY_REDIS_URL")
        cache_ttl = int(os.getenv("GATEWAY_REDIS_CACHE_TTL_SECONDS", "300"))
        return PostgresKeyStore(dsn=dsn, redis_url=redis_url, cache_ttl_seconds=cache_ttl)

    raise RuntimeError(f"Unsupported GATEWAY_KEY_STORE: {backend}")


def build_usage_store() -> UsageStore:
    if os.getenv("GATEWAY_USAGE_TRACKING_ENABLED", "true").lower() not in {"1", "true", "yes", "on"}:
        return NullUsageStore()

    backend = os.getenv("GATEWAY_USAGE_STORE", os.getenv("GATEWAY_KEY_STORE", "sqlite")).lower()

    if backend == "sqlite":
        return SQLiteUsageStore(Path(os.getenv("GATEWAY_USAGE_SQLITE_PATH", os.getenv("GATEWAY_SQLITE_PATH", str(DEFAULT_SQLITE_PATH)))))

    if backend in {"postgres", "postgresql"}:
        dsn = os.getenv("GATEWAY_USAGE_POSTGRES_DSN", os.getenv("GATEWAY_POSTGRES_DSN"))
        if not dsn:
            raise RuntimeError("GATEWAY_POSTGRES_DSN is required when GATEWAY_USAGE_STORE=postgres")
        return PostgresUsageStore(dsn=dsn)

    raise RuntimeError(f"Unsupported GATEWAY_USAGE_STORE: {backend}")


