from __future__ import annotations

import os
import sqlite3
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

import psycopg
import redis


DEFAULT_SQLITE_PATH = Path("gateway_keys.db")


class KeyStore(Protocol):
    def initialize(self) -> None:
        ...

    def add_key_hash(self, key_hash: str, name: str | None = None) -> None:
        ...

    def has_key_hash(self, key_hash: str) -> bool:
        ...


CREATE_KEYS_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS gateway_keys (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    key_hash TEXT NOT NULL UNIQUE,
    name TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
)
"""


SQLITE_CREATE_KEYS_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS gateway_keys (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    key_hash TEXT NOT NULL UNIQUE,
    name TEXT,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
)
"""


@dataclass
class SQLiteKeyStore:
    path: Path = DEFAULT_SQLITE_PATH

    def initialize(self) -> None:
        with self.connect() as conn:
            conn.execute(SQLITE_CREATE_KEYS_TABLE_SQL)

    def add_key_hash(self, key_hash: str, name: str | None = None) -> None:
        with self.connect() as conn:
            conn.execute(
                """
                INSERT INTO gateway_keys (key_hash, name)
                VALUES (?, ?)
                ON CONFLICT(key_hash) DO UPDATE SET name = excluded.name
                """,
                (key_hash, name),
            )

    def has_key_hash(self, key_hash: str) -> bool:
        with self.connect() as conn:
            row = conn.execute(
                "SELECT 1 FROM gateway_keys WHERE key_hash = ? LIMIT 1",
                (key_hash,),
            ).fetchone()
        return row is not None

    def connect(self) -> sqlite3.Connection:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        return sqlite3.connect(self.path)


@dataclass
class PostgresKeyStore:
    dsn: str
    redis_url: str | None = None
    cache_ttl_seconds: int = 300

    def __post_init__(self) -> None:
        self._redis = redis.Redis.from_url(self.redis_url) if self.redis_url else None

    def initialize(self) -> None:
        with psycopg.connect(self.dsn) as conn:
            conn.execute(CREATE_KEYS_TABLE_SQL)

    def add_key_hash(self, key_hash: str, name: str | None = None) -> None:
        with psycopg.connect(self.dsn) as conn:
            conn.execute(
                """
                INSERT INTO gateway_keys (key_hash, name)
                VALUES (%s, %s)
                ON CONFLICT(key_hash) DO UPDATE SET name = EXCLUDED.name
                """,
                (key_hash, name),
            )
        self.cache_key_hash(key_hash)

    def has_key_hash(self, key_hash: str) -> bool:
        cache_key = self.cache_key(key_hash)
        if self._redis and self._redis.get(cache_key):
            return True

        with psycopg.connect(self.dsn) as conn:
            row = conn.execute(
                "SELECT 1 FROM gateway_keys WHERE key_hash = %s LIMIT 1",
                (key_hash,),
            ).fetchone()

        if row is not None:
            self.cache_key_hash(key_hash)
            return True
        return False

    def cache_key_hash(self, key_hash: str) -> None:
        if self._redis:
            self._redis.setex(self.cache_key(key_hash), self.cache_ttl_seconds, "1")

    @staticmethod
    def cache_key(key_hash: str) -> str:
        return f"ai-gateway:key:{key_hash}"


def build_key_store() -> KeyStore:
    backend = os.getenv("GATEWAY_KEY_STORE", "sqlite").lower()

    if backend == "sqlite":
        return SQLiteKeyStore(Path(os.getenv("GATEWAY_SQLITE_PATH", str(DEFAULT_SQLITE_PATH))))

    if backend in {"postgres", "postgresql"}:
        dsn = os.getenv("GATEWAY_POSTGRES_DSN")
        if not dsn:
            raise RuntimeError("GATEWAY_POSTGRES_DSN is required when GATEWAY_KEY_STORE=postgres")

        redis_url = os.getenv("GATEWAY_REDIS_URL")
        cache_ttl = int(os.getenv("GATEWAY_REDIS_CACHE_TTL_SECONDS", "300"))
        return PostgresKeyStore(dsn=dsn, redis_url=redis_url, cache_ttl_seconds=cache_ttl)

    raise RuntimeError(f"Unsupported GATEWAY_KEY_STORE: {backend}")
