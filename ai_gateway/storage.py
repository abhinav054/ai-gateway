@dataclass
class PostgresKeyStore:
    dsn: str
    redis_url: str | None = None
    cache_ttl_seconds: int = 300

    def __post_init__(self) -> None:
        self._redis = redis.Redis.from_url(self.redis_url) if self.redis_url else None

    def initialize(self) -> None:
        with psycopg.connect(self.dsn) as conn:
            conn.execute(CREATE_KEYS_TABLE_SQL)

    def add_key_hash(self, key_hash: str, name: str | None = None) -> None:
        with psycopg.connect(self.dsn) as conn:
            conn.execute(
                """
                INSERT INTO gateway_keys (key_hash, name)
                VALUES (%s, %s)
                ON CONFLICT(key_hash) DO UPDATE SET name = EXCLUDED.name
                """,
                (key_hash, name),
            )
        self.cache_key_hash(key_hash)

    def has_key_hash(self, key_hash: str) -> bool:
        cache_key = self.cache_key(key_hash)
        if self._redis and self._redis.get(cache_key):
            return True

        with psycopg.connect(self.dsn) as conn:
            row = conn.execute(
                "SELECT 1 FROM gateway_keys WHERE key_hash = %s LIMIT 1",
                (key_hash,),
            ).fetchone()

        if row is not None:
            self.cache_key_hash(key_hash)
            return True
        return False

    def cache_key_hash(self, key_hash: str) -> None:
        if self._redis:
            self._redis.setex(self.cache_key(key_hash), self.cache_ttl_seconds, "1")

    @staticmethod
    def cache_key(key_hash: str) -> str:
        return f"ai-gateway:key:{key_hash}"


