from __future__ import annotations

import os
import sqlite3
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

import psycopg
import redis


DEFAULT_SQLITE_PATH = Path("gateway_keys.db")


class KeyStore(Protocol):
    def initialize(self) -> None:
        ...

    def add_key_hash(self, key_hash: str, name: str | None = None) -> None:
        ...

    def has_key_hash(self, key_hash: str) -> bool:
        ...


class UsageStore(Protocol):
    def initialize(self) -> None:
        ...

    def record_usage(
        self,
        *,
        key_hash: str,
        method: str,
        path: str,
        model: str | None,
        status_code: int,
        input_tokens: int | None,
        output_tokens: int | None,
        total_tokens: int | None,
        request_id: str | None,
    ) -> None:
        ...


CREATE_KEYS_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS gateway_keys (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    key_hash TEXT NOT NULL UNIQUE,
    name TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
)
"""


CREATE_USAGE_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS token_usage (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    key_hash TEXT NOT NULL,
    method TEXT NOT NULL,
    path TEXT NOT NULL,
    model TEXT,
    status_code INTEGER NOT NULL,
    input_tokens INTEGER,
    output_tokens INTEGER,
    total_tokens INTEGER,
    request_id TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
)
"""


SQLITE_CREATE_KEYS_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS gateway_keys (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    key_hash TEXT NOT NULL UNIQUE,
    name TEXT,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
)
"""


SQLITE_CREATE_USAGE_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS token_usage (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    key_hash TEXT NOT NULL,
    method TEXT NOT NULL,
    path TEXT NOT NULL,
    model TEXT,
    status_code INTEGER NOT NULL,
    input_tokens INTEGER,
    output_tokens INTEGER,
    total_tokens INTEGER,
    request_id TEXT,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
)
"""


@dataclass
class SQLiteKeyStore:
    path: Path = DEFAULT_SQLITE_PATH

    def initialize(self) -> None:
        with self.connect() as conn:
            conn.execute(SQLITE_CREATE_KEYS_TABLE_SQL)

    def add_key_hash(self, key_hash: str, name: str | None = None) -> None:
        with self.connect() as conn:
            conn.execute(
                """
                INSERT INTO gateway_keys (key_hash, name)
                VALUES (?, ?)
                ON CONFLICT(key_hash) DO UPDATE SET name = excluded.name
                """,
                (key_hash, name),
            )

    def has_key_hash(self, key_hash: str) -> bool:
        with self.connect() as conn:
            row = conn.execute(
                "SELECT 1 FROM gateway_keys WHERE key_hash = ? LIMIT 1",
                (key_hash,),
            ).fetchone()
        return row is not None

    def connect(self) -> sqlite3.Connection:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        return sqlite3.connect(self.path)


