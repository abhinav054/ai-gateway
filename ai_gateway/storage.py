@dataclass
class PostgresKeyStore:
    def list_keys(self, gateway_id: str) -> list[dict]:
        with psycopg.connect(self.dsn) as conn:
            rows = conn.execute(
                "SELECT key_hash, name, created_at FROM gateway_keys WHERE gateway_id = %s ORDER BY created_at DESC, id DESC",
                (gateway_id,),
            ).fetchall()
        return [{"id": row[0], "name": row[1], "createdAt": str(row[2])} for row in rows]

    dsn: str
    redis_url: str | None = None
    cache_ttl_seconds: int = 300

    def __post_init__(self) -> None:
        self._redis = redis.Redis.from_url(self.redis_url) if self.redis_url else None

    def initialize(self) -> None:
        with psycopg.connect(self.dsn) as conn:
            conn.execute("CREATE TABLE IF NOT EXISTS gateway_objects (id TEXT PRIMARY KEY, definition JSONB NOT NULL)")
            conn.execute(CREATE_KEYS_TABLE_SQL)
            conn.execute(CREATE_ROUTES_TABLE_SQL)
            ensure_postgres_columns(
                conn,
                "gateway_keys",
                {
                    "provider": "TEXT",
                    "api_key": "TEXT",
                    "base_url": "TEXT",
                    "gateway_id": "TEXT REFERENCES gateway_objects(id)",
                },
            )

    def add_key_hash(
        self,
        key_hash: str,
        name: str | None = None,
        provider: str | None = None,
        api_key: str | None = None,
        base_url: str | None = None,
        gateway_id: str | None = None,
    ) -> None:
        with psycopg.connect(self.dsn) as conn:
            conn.execute(
                """
                INSERT INTO gateway_keys (key_hash, name, provider, api_key, base_url, gateway_id)
                VALUES (%s, %s, %s, %s, %s, %s)
                ON CONFLICT(key_hash) DO UPDATE SET
                    name = EXCLUDED.name,
                    provider = EXCLUDED.provider,
                    api_key = EXCLUDED.api_key,
                    base_url = EXCLUDED.base_url,
                    gateway_id = EXCLUDED.gateway_id
                """,
                (key_hash, name, provider, api_key, base_url, gateway_id),
            )
        self.cache_key_hash(key_hash)

    def has_key_hash(self, key_hash: str) -> bool:
        cache_key = self.cache_key(key_hash)
        if self._redis and self._redis.get(cache_key):
            return True

        with psycopg.connect(self.dsn) as conn:
            row = conn.execute(
                "SELECT 1 FROM gateway_keys WHERE key_hash = %s LIMIT 1",
                (key_hash,),
            ).fetchone()

        if row is not None:
            self.cache_key_hash(key_hash)
            return True
        return False

    def get_key(self, key_hash: str) -> GatewayKey | None:
        with psycopg.connect(self.dsn) as conn:
            row = conn.execute(
                """
                SELECT key_hash, name, provider, api_key, base_url, gateway_id
                FROM gateway_keys
                WHERE key_hash = %s
                LIMIT 1
                """,
                (key_hash,),
            ).fetchone()

        if row is not None:
            self.cache_key_hash(key_hash)
        return gateway_key_from_row(row)

    def upsert_route(self, name: str, provider: str | None, api_key: str, base_url: str) -> None:
        with psycopg.connect(self.dsn) as conn:
            conn.execute(
                """
                INSERT INTO gateway_routes (name, provider, api_key, base_url, updated_at)
                VALUES (%s, %s, %s, %s, CURRENT_TIMESTAMP)
                ON CONFLICT(name) DO UPDATE SET
                    provider = EXCLUDED.provider,
                    api_key = EXCLUDED.api_key,
                    base_url = EXCLUDED.base_url,
                    updated_at = CURRENT_TIMESTAMP
                """,
                (name, provider, api_key, base_url),
            )

    def get_route(self, name: str) -> RoutingConfig | None:
        with psycopg.connect(self.dsn) as conn:
            row = conn.execute(
                """
                SELECT name, provider, api_key, base_url
                FROM gateway_routes
                WHERE name = %s
                LIMIT 1
                """,
                (name,),
            ).fetchone()
        return routing_config_from_row(row)

    def list_routes(self) -> list[RoutingConfig]:
        with psycopg.connect(self.dsn) as conn:
            rows = conn.execute(
                "SELECT name, provider, api_key, base_url FROM gateway_routes ORDER BY name"
            ).fetchall()
        return [RoutingConfig(*row) for row in rows]

    def upsert_gateway(self, gateway: Gateway) -> None:
        with psycopg.connect(self.dsn) as conn:
            conn.execute(
                "INSERT INTO gateway_objects (id, definition) VALUES (%s, %s) "
                "ON CONFLICT(id) DO UPDATE SET definition = EXCLUDED.definition",
                (gateway.id, Jsonb(gateway.model_dump())),
            )

    def get_gateway(self, gateway_id: str) -> Gateway | None:
        with psycopg.connect(self.dsn) as conn:
            row = conn.execute("SELECT definition FROM gateway_objects WHERE id = %s", (gateway_id,)).fetchone()
        return Gateway.model_validate(row[0]) if row else None

    def cache_key_hash(self, key_hash: str) -> None:
        if self._redis:
            self._redis.setex(self.cache_key(key_hash), self.cache_ttl_seconds, "1")

    @staticmethod
    def cache_key(key_hash: str) -> str:
        return f"ai-gateway:key:{key_hash}"


def ensure_sqlite_columns(conn: sqlite3.Connection, table: str, columns: dict[str, str]) -> None:
    existing = {row[1] for row in conn.execute(f"PRAGMA table_info({table})").fetchall()}
    for name, definition in columns.items():
        if name not in existing:
            conn.execute(f"ALTER TABLE {table} ADD COLUMN {name} {definition}")


def ensure_postgres_columns(conn: psycopg.Connection, table: str, columns: dict[str, str]) -> None:
    for name, definition in columns.items():
        conn.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {name} {definition}")


def gateway_key_from_row(row: Any) -> GatewayKey | None:
    if row is None:
        return None
    return GatewayKey(
        key_hash=row[0],
        name=row[1],
        provider=row[2],
        api_key=row[3],
        base_url=row[4],
        gateway_id=row[5],
    )


def routing_config_from_row(row: Any) -> RoutingConfig | None:
    if row is None:
        return None
    return RoutingConfig(
        name=row[0],
        provider=row[1],
        api_key=row[2],
        base_url=row[3],
    )


